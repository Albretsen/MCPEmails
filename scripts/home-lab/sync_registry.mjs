#!/usr/bin/env node
// Copies each variant's picker label (apps/web/components/home-lab/vNN/meta.mjs)
// into apps/web/components/home-lab/registry.mjs. The picker imports only the
// registry: importing anything inside a variant folder from the home route pulled
// every variant's CSS onto the home page. `--check` fails if the registry is stale.
import { writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const lab = path.join(root, 'apps/web/components/home-lab');
const metas = [];
for (let i = 1; i <= 10; i++) {
  const id = `v${String(i).padStart(2, '0')}`;
  const { meta } = await import(pathToFileURL(path.join(lab, id, 'meta.mjs')).href);
  metas.push({ id: meta.id, name: meta.name, concept: meta.concept });
}
const out = `// Generated by scripts/home-lab/sync_registry.mjs from each vNN/meta.mjs. Do not edit.
// The picker imports this file, never a variant folder (see that script).
export const HOME_LAB_VARIANTS = ${JSON.stringify(
  [{ id: 'v00', name: 'v00 (current)', concept: "Today's production homepage." }, ...metas],
  null,
  2,
)};
`;
const target = path.join(root, 'apps/web/components/home-lab-shell/registry.mjs');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== out) {
    console.error('registry.mjs is stale: run node scripts/home-lab/sync_registry.mjs');
    process.exit(1);
  }
  console.log('registry.mjs is up to date');
} else {
  writeFileSync(target, out);
  console.log('wrote', path.relative(root, target));
}
