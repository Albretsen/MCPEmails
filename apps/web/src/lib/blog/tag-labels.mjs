/** The locales the table is written in (for the parity test). */
export const TAG_LABEL_LOCALES = Object.freeze(Object.keys(LABELS));

/** True when the table spells `tag` in `locale` (even when the spelling equals the English key, as "Tutorial" in Spanish). */
export function hasTagLabel(tag, locale) {
  return Boolean(LABELS[locale]) && Object.hasOwn(LABELS[locale], tag);
}

/** The word on the chip for `tag` in `locale`; the English key when there is none. */
export function tagLabel(tag, locale) {
  return LABELS[locale]?.[tag] ?? tag;
}

/** `{ tag: label }` for every tag in `tags`, the shape the client components take. */
export function tagLabelMap(tags, locale) {
  const out = {};
  for (const tag of new Set(tags)) out[tag] = tagLabel(tag, locale);
  return out;
}
