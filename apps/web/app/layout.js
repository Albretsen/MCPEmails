    title: 'mcpemails · Connect Gmail, iCloud & IMAP to Claude',
    description: 'Give Claude, Cursor, or any MCP client real access to your inbox: read, send, search, and organize email in Gmail, Fastmail, iCloud, and IMAP. Outlook is in progress.',
    url: APP_URL,
