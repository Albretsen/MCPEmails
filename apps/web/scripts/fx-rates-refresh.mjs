#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Regenerate src/lib/analytics/fx-rates.ts, the monthly exchange rate table
// that src/lib/analytics/fx.ts converts revenue with.
//
// WHY A CHECKED-IN TABLE AND NOT A LIVE FETCH. The growth board renders on a
// cached server read every few minutes; a network call to a rate service on
// that path is one more thing that can take a money tile down, and a rate
// that changes between two renders makes MRR wobble for no business reason.
// A month's average rate is a fact once the month is over, so it belongs in
// the repo, reviewed like any other constant.
//
// SOURCE. European Central Bank reference rates, served by frankfurter.dev
// (base EUR, one quote per TARGET business day). For each calendar month the
// script averages the daily USD-per-unit cross rate (USD/EUR divided by X/EUR)
// over the business days the ECB published, and rounds to six significant
// figures. The current, unfinished month is an average of the days so far.
//
// Run from apps/web, then commit the regenerated file:
//
//   node scripts/fx-rates-refresh.mjs                 # 2026-01-01 to today
//   node scripts/fx-rates-refresh.mjs 2026-01-01 2026-10-23
//
// Read-only against the network, writes exactly one file.
// ---------------------------------------------------------------------------

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

/** Currencies the table carries. USD is implicit (always 1). */
export const FX_CURRENCIES = ['EUR', 'GBP', 'NOK', 'CHF', 'SEK', 'DKK', 'PLN', 'CZK', 'AUD', 'CAD'];

/**
 * Monthly average USD per one unit of each currency, from a frankfurter
 * time-series response with base EUR. Pure, so the test can feed it a fixture.
 */
export function monthlyAverages(series, currencies = FX_CURRENCIES, { from, to } = {}) {
  if (series?.base !== 'EUR' || !series.rates) throw new Error('expected a frankfurter series with base EUR');
  const sums = new Map();
  for (const [day, quotes] of Object.entries(series.rates)) {
    // frankfurter answers a range starting on a holiday with the business day
    // before it, so the response can open in the previous month.
    if (from && day < from) continue;
    if (to && day > to) continue;
    const usdPerEur = quotes.USD;
    if (!Number.isFinite(usdPerEur)) continue;
    const month = day.slice(0, 7);
    const row = sums.get(month) ?? new Map();
    for (const code of currencies) {
      const perEur = code === 'EUR' ? 1 : quotes[code];
      if (!Number.isFinite(perEur) || perEur <= 0) continue;
      const acc = row.get(code) ?? { total: 0, days: 0 };
      acc.total += usdPerEur / perEur;
      acc.days += 1;
      row.set(code, acc);
    }
    sums.set(month, row);
  }
  /** @type {Record<string, Record<string, number>>} */
  const table = {};
  for (const month of [...sums.keys()].sort()) {
    table[month] = {};
    for (const code of currencies) {
      const acc = sums.get(month).get(code);
      if (acc) table[month][code.toLowerCase()] = Number((acc.total / acc.days).toPrecision(6));
    }
  }
  return table;
}

/** The TypeScript module fx.ts imports. */
export function renderModule(table, { from, to }) {
  const months = Object.keys(table).sort();
  const lines = months.map((month) => {
    const pairs = Object.entries(table[month]).map(([code, rate]) => `${code}: ${rate}`);
    return `  '${month}': { ${pairs.join(', ')} },`;
  });
  return [
    '/**',
    ' * GENERATED by apps/web/scripts/fx-rates-refresh.mjs. Do not edit by hand.',
    ' *',
    ' * Monthly average USD per one unit of each currency, from ECB reference',
    ` * rates via frankfurter.dev, ${from} to ${to}. See fx.ts for how it is used.`,
    ' */',
    'export const USD_PER_UNIT_BY_MONTH: Readonly<Record<string, Readonly<Record<string, number>>>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

async function main() {
  const today = new Date().toISOString().slice(0, 10);
  const from = process.argv[2] ?? '2026-01-01';
  const to = process.argv[3] ?? today;
  const url = `https://api.frankfurter.dev/v1/${from}..${to}?base=EUR`;
  const response = await fetch(url, { redirect: 'follow' });
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  const table = monthlyAverages(await response.json(), FX_CURRENCIES, { from, to });
  const months = Object.keys(table);
  if (months.length === 0) throw new Error('no rates in the response');
  const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/lib/analytics/fx-rates.ts');
  writeFileSync(target, renderModule(table, { from, to }));
  console.log(`wrote ${months.length} months (${months[0]} to ${months[months.length - 1]}) to ${target}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
